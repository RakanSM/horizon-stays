const AMENITY_MAPS: Partial<Record<Lang, Record<string, string>>> = {
  ar: AMENITY_AR,
  zh: AMENITY_ZH,
  fr: AMENITY_FR,
  es: AMENITY_ES,
};

export function localizeAmenity(a: string, lang: Lang): string {
  if (lang === "en") return a;
  const map = AMENITY_MAPS[lang];
  if (!map) return a;
  const key = a.trim().toLowerCase();
  return map[key] || a;
}
