export type StrKey = keyof typeof STR;

type LangCtx = {
  lang: Lang;
  dir: "rtl" | "ltr";
  t: (k: StrKey) => string;
  setLang: (l: Lang) => void;
};

const Ctx = createContext<LangCtx>({
  lang: "ar",
  dir: "rtl",
  t: (k) => STR[k]?.ar ?? k,
  setLang: () => {},
});

const VALID: Lang[] = ["ar", "en", "zh", "fr", "es"];

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("hs_lang");
    return VALID.includes(saved as Lang) ? (saved as Lang) : "ar";
  });
  const dir: "rtl" | "ltr" = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const setLang = (l: Lang) => {
    localStorage.setItem("hs_lang", l);
    setLangState(l);
  };

  const t = (k: StrKey) => STR[k]?.[lang] ?? STR[k]?.en ?? k;

  return <Ctx.Provider value={{ lang, dir, t, setLang }}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}

/** Localized property name (AR uses Arabic name; other languages fall back to English) */
export function propName(p: { name_ar: string; name_en: string }, lang: Lang): string {
  return lang === "ar" ? p.name_ar || p.name_en : p.name_en || p.name_ar;
}

/** Format date -> YYYY-MM-DD */
export function fmtDate(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

